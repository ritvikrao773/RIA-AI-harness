# Builds installer.exe + uninstaller.exe and assembles release\ for distribution.
# NOTE: the payload is NOT embedded — installer.exe ships beside ria.exe in
# the zip (like ordinary installers). An exe that unpacks another exe from
# its own body gets flagged as a dropper by antivirus.
# Needs: dist\ria.exe (run build-exe.ps1 first), the .NET Framework compiler (csc).
$ErrorActionPreference = "Stop"
Set-Location $PSScriptRoot\..

if (-not (Test-Path "dist\ria.exe")) { throw "dist\ria.exe missing - run: powershell -ExecutionPolicy Bypass -File build-exe.ps1" }

$csc = @(
  "C:\Windows\Microsoft.NET\Framework64\v4.0.30319\csc.exe",
  "C:\Windows\Microsoft.NET\Framework\v4.0.30319\csc.exe"
) | Where-Object { Test-Path $_ } | Select-Object -First 1
if (-not $csc) { throw "csc.exe not found (.NET Framework 4.x required)" }

# Version comes from package.json — single source of truth.
$version = (Get-Content package.json -Raw | ConvertFrom-Json).version
@"
// Generated by build-installer.ps1 — do not edit.
static class RiaVersion { public const string Text = "$version"; }
"@ | Set-Content -Encoding ASCII installer\Version.cs
Write-Host "version: $version"

New-Item -ItemType Directory release -Force | Out-Null

Write-Host "compiling installer.exe…"
& $csc /nologo /target:exe /platform:anycpu /optimize+ `
  /win32icon:assets\ria.ico `
  /out:release\installer.exe installer\installer.cs installer\Version.cs
if ($LASTEXITCODE -ne 0) { throw "installer.exe compile failed" }

Write-Host "compiling uninstaller.exe…"
& $csc /nologo /target:exe /platform:anycpu /optimize+ `
  /win32icon:assets\ria.ico `
  /out:release\uninstaller.exe installer\uninstaller.cs installer\Version.cs
if ($LASTEXITCODE -ne 0) { throw "uninstaller.exe compile failed" }

# Also ship the plain payload next to the installer (repo-hosted alternative).
Copy-Item dist\ria.exe release\ria.exe -Force

# Distribution zip: one file users download and extract.
$stage = "installer\stage"
if (Test-Path $stage) { Remove-Item $stage -Recurse -Force }
New-Item -ItemType Directory $stage | Out-Null
Copy-Item release\installer.exe, release\uninstaller.exe, release\ria.exe $stage
Compress-Archive -Path "$stage\*" -DestinationPath release\ria-setup-windows.zip -Force
Remove-Item $stage -Recurse -Force

Write-Host "`nrelease contents:"
Get-ChildItem release | ForEach-Object { "  {0,12:N0}  {1}" -f $_.Length, $_.Name }
